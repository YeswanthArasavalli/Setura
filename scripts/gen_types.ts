/**
 * scripts/gen_types.ts - encoding-safe wrapper around
 * `supabase gen types typescript --local`.
 *
 *   deno task gen:types
 *
 * Why this exists instead of a shell redirect:
 *
 * The previous task piped the CLI through PowerShell:
 *
 *     supabase gen types typescript --local |
 *         Set-Content -Path ... -Encoding utf8
 *
 * On Windows PowerShell 5.1 a bare `>` redirect writes UTF-16LE, and
 * `Set-Content -Encoding utf8` writes UTF-8 *with* a BOM. The committed
 * database.generated.ts was in fact UTF-16LE (BOM ff fe, null-interleaved
 * ASCII, 499894 bytes for ~250 KB of text). Deno happens to tolerate that,
 * but everything else does not: git sees a binary blob and stops producing
 * diffs, grep and ripgrep miss every match, and the file silently doubles
 * in size on each commit.
 *
 * This script takes the CLI's stdout as bytes, decodes it explicitly
 * (tolerating a UTF-8 or UTF-16LE BOM in case the CLI's own behaviour
 * changes), normalizes to LF, and writes UTF-8 with no BOM. The output
 * encoding is therefore a property of this script rather than of whichever
 * shell happens to invoke it.
 *
 * Flags:
 *   --check   do not write; exit 1 if the file on disk differs from what
 *             the database would produce, or is not BOM-less UTF-8.
 */

const OUT_PATH = new URL(
  "../supabase/functions/_shared/database.generated.ts",
  import.meta.url,
);

const HEADER = [
  "// Generated by `deno task gen:types` - do not hand-edit.",
  "// Regenerate after every migration that changes a table, view,",
  "// enum or function signature.",
  "",
].join("\n");

/** Decode CLI output, tolerating a BOM in any of the usual encodings. */
function decode(bytes: Uint8Array): string {
  if (bytes.length >= 2 && bytes[0] === 0xff && bytes[1] === 0xfe) {
    return new TextDecoder("utf-16le").decode(bytes.subarray(2));
  }
  if (bytes.length >= 2 && bytes[0] === 0xfe && bytes[1] === 0xff) {
    return new TextDecoder("utf-16be").decode(bytes.subarray(2));
  }
  if (
    bytes.length >= 3 && bytes[0] === 0xef && bytes[1] === 0xbb &&
    bytes[2] === 0xbf
  ) {
    return new TextDecoder("utf-8").decode(bytes.subarray(3));
  }
  return new TextDecoder("utf-8").decode(bytes);
}

function normalize(text: string): string {
  return text.replace(/\r\n/g, "\n").replace(/\s+$/, "") + "\n";
}

async function generate(): Promise<string> {
  const cmd = new Deno.Command("supabase", {
    args: ["gen", "types", "typescript", "--local"],
    stdout: "piped",
    stderr: "piped",
  });
  const { code, stdout, stderr } = await cmd.output();
  if (code !== 0) {
    const err = new TextDecoder().decode(stderr).trim();
    throw new Error(
      `supabase gen types failed (exit ${code}). Is the local stack ` +
        `running? Output:\n${err}`,
    );
  }
  const body = normalize(decode(stdout));
  if (!body.includes("export type Database")) {
    throw new Error(
      "supabase gen types produced no Database type - refusing to write a " +
        "truncated file.",
    );
  }
  return `${HEADER}${body}`;
}

const checkOnly = Deno.args.includes("--check");

if (checkOnly) {
  let onDisk: Uint8Array;
  try {
    onDisk = await Deno.readFile(OUT_PATH);
  } catch {
    console.error(
      "database.generated.ts is missing - run: deno task gen:types",
    );
    Deno.exit(1);
  }
  if (
    onDisk.length >= 2 &&
    ((onDisk[0] === 0xff && onDisk[1] === 0xfe) ||
      (onDisk[0] === 0xfe && onDisk[1] === 0xff))
  ) {
    console.error(
      "database.generated.ts is UTF-16 encoded. Regenerate with: " +
        "deno task gen:types",
    );
    Deno.exit(1);
  }
  if (onDisk[0] === 0xef && onDisk[1] === 0xbb && onDisk[2] === 0xbf) {
    console.error(
      "database.generated.ts has a UTF-8 BOM. Regenerate with: " +
        "deno task gen:types",
    );
    Deno.exit(1);
  }
  const expected = new TextEncoder().encode(await generate());
  if (
    expected.length !== onDisk.length ||
    !expected.every((b, i) => b === onDisk[i])
  ) {
    console.error(
      "database.generated.ts is stale - regenerate with: deno task gen:types",
    );
    Deno.exit(1);
  }
  console.log("database.generated.ts is UTF-8 and up to date.");
} else {
  const text = await generate();
  // TextEncoder emits UTF-8 with no BOM, unconditionally.
  await Deno.writeFile(OUT_PATH, new TextEncoder().encode(text));
  console.log(
    `Wrote ${OUT_PATH.pathname.split("/").pop()} ` +
      `(${text.length} chars, UTF-8, no BOM)`,
  );
}
