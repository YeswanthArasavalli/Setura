SELECT to_char(now(),'YYYY-MM-DD"T"HH24:MI:SS"Z"')
  || ' pend='  || (SELECT count(*) FROM public.job_queue WHERE status='pending')
  || ' proc='  || (SELECT count(*) FROM public.job_queue WHERE status='processing')
  || ' done='  || (SELECT count(*) FROM public.job_queue WHERE status='completed')
  || ' dead='  || (SELECT count(*) FROM public.job_queue WHERE status='dead')
  || ' cron_ok_1h='   || (SELECT count(*) FROM cron.job_run_details WHERE status='succeeded' AND start_time > now() - interval '60 minutes')
  || ' cron_bad_1h='  || (SELECT count(*) FROM cron.job_run_details WHERE status <> 'succeeded' AND start_time > now() - interval '60 minutes')
  || ' leases_open='  || (SELECT count(*) FROM public.worker_job_leases WHERE outcome IS NULL)
  || ' leases_orphan='|| (SELECT count(*) FROM public.worker_job_leases l WHERE l.outcome IS NULL AND NOT EXISTS (SELECT 1 FROM public.job_queue j WHERE j.id = l.job_queue_id AND j.status = 'processing'))
  || ' workers_active=' || (SELECT count(*) FROM public.worker_registry WHERE status='active')
  || ' hb_latest=' || (SELECT COALESCE(max(last_heartbeat_at)::text,'-') FROM public.worker_registry) AS sample;
